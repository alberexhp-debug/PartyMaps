export type ClaveI18n = keyof typeof D

// Resolución pura (sin hook): útil para textos guardados por clave (notis).
export function traducir(k: ClaveI18n, idioma: Idioma): string {
  if (idioma === 'ja') return JA[k] ?? D[k]?.[0] ?? k
  return D[k]?.[idioma === 'en' ? 1 : 0] ?? D[k]?.[0] ?? k
}

// Sustitución simple de {param} en un texto ya traducido.
export function conParams(texto: string, params?: Record<string, string | number>): string {
  if (!params) return texto
  return texto.replace(/\{(\w+)\}/g, (m, p) => (p in params ? String(params[p]) : m))
}

export function useT() {
  const idioma = useDemoStore(s => s.idioma)
  const t = (k: ClaveI18n): string => traducir(k, idioma)
  return { t, idioma }
}

