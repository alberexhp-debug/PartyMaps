import { createServerClient } from '@supabase/ssr'
import { createClient } from '@supabase/supabase-js'
import { cookies } from 'next/headers'

/**
 * Cliente service_role PURO, sin cookies de sesión. PostgREST usa el
 * service_role como Authorization → ignora RLS. Úsalo para operaciones
 * privilegiadas (alta de locales, cuentas, etc.) DESPUÉS de haber
 * verificado la identidad por separado. OJO: nunca exponer al cliente.
 *
 * (createAdminSupabaseClient sí arrastra las cookies, por lo que cuando hay
 *  un usuario logueado corre como ese usuario y SÍ aplica RLS.)
 */
export function createServiceRoleClient() {
  return createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.SUPABASE_SERVICE_ROLE_KEY!,
    { auth: { persistSession: false, autoRefreshToken: false } }
  )
}

export async function createServerSupabaseClient() {
  const cookieStore = await cookies()
  return createServerClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        getAll() { return cookieStore.getAll() },
        setAll(cookiesToSet) {
          try {
            cookiesToSet.forEach(({ name, value, options }) =>
              cookieStore.set(name, value, options)
            )
          } catch {}
        },
      },
    }
  )
}

